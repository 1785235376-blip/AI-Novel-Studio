"""Deterministic Ren'Py 8.5.4 project renderer for target RENPY_8_5_4_PROJECT_V1.

The renderer is a restricted format conversion over the authorized interactive
story snapshot handed down by app/experimental/interactive_renpy_export.py. It
reuses the product story authority (StorySpec, compile_story, renpy_text,
renpy_expression) and therefore never re-implements typed condition semantics,
never executes story code, opens no files, writes nothing outside the returned
file dictionary, packages no media bytes and never bundles the Ren'Py engine.

The generated project is a complete Ren'Py project skeleton (game/) that the
reader opens with an installed Ren'Py 8.5.4 SDK launcher. Every user-authored
string is emitted through the authority renpy_text escape as a single string
literal; project paths are ASCII and are re-validated by the export contract.
"""
