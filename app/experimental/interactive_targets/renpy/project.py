def render_script(project, characters, meta, include_witness=True):
    """Render game/script.rpy: label start resets state, then every node label."""
    spec, nodes = project['spec'], project['nodes']
    compiled, labels, names = project['compiled'], project['labels'], project['names']
    max_steps = int(spec['max_steps'])
    lines = _header(project, meta, include_witness)
    lines += ['', '# Approved typed variables (declared before any label uses them).', 'default ans_steps = 0']
    for variable in spec['variables']:
        lines.append('default ' + names[variable['name']] + ' = ' + scalar_literal(variable['initial']))
    lines += ['', 'label start:',
              '    # A new game and a replay always reset the step counter and variables.',
              '    $ ans_steps = 0']
    for variable in spec['variables']:
        lines.append('    $ ' + names[variable['name']] + ' = ' + scalar_literal(variable['initial']))
    lines += ['    # Entry node from the approved story spec.', '    jump ' + labels[spec['entry_node_id']], '']
    for node_id, node in nodes.items():
        lines.append('label ' + labels[node_id] + ':')
        lines.append('    # node ' + comment_text(node_id, 160) + ' | ' + comment_text(node['title'], 120))
        speaker = characters.get(node.get('character_id')) if node.get('character_id') else None
        if node['dialogue']:
            prefix = literal(speaker) + ' ' if isinstance(speaker, str) and speaker else ''
            lines.append('    ' + prefix + literal(node['dialogue']))
        if node['ending']:
            lines += ['    # ending: display the approved ending text, then return to the main menu.',
                      '    ' + literal(node['ending']), '    return', '']
            continue
        conditions = [renpy_expression(compiled[(node_id, choice['id'])], names) for choice in node['choices']]
        lines += ['    # Bounded step cap: the generated script never exceeds the approved step budget.',
                  '    if ans_steps >= ' + str(max_steps) + ':',
                  '        ' + literal(STEP_CAP_MESSAGE),
                  '        return',
                  '    # Conditional menu: a choice is shown only when its approved typed condition is true.',
                  '    if not (' + (' or '.join(conditions) if conditions else 'False') + '):',
                  '        ' + literal(NO_CHOICE_MESSAGE),
                  '        return',
                  '    menu:']
        for choice, condition in zip(node['choices'], conditions):
            lines.append('        ' + literal(choice['label']) + ' if ' + condition + ':')
            lines.append('            $ ans_steps += 1')
            for name, value in choice['assignments'].items():
                lines.append('            $ ' + names[name] + ' = ' + scalar_literal(value))
            lines.append('            jump ' + labels[choice['target']])
        lines.append('')
    return '\n'.join(lines) + '\n'


def _slug(value):
    slug = re.sub(r'[^A-Za-z0-9_]', '_', value or 'story')[:40].strip('_')
    return slug or 'story'


def render_options(project, meta):
    """Render game/options.rpy: minimum project configuration, no engine template."""
    spec = project['spec']
    title = spec['title']
    slug = _slug(str(meta.get('story_id') or 'story'))
    version = FORMAT_VERSION + '-r' + str(meta.get('revision') or 1)
    lines = [
        '# Generated minimal Ren\'Py project configuration for target ' + TARGET_ID + '.',
        '# No Ren\'Py engine or launcher template file is copied into this project and the',
        '# engine itself is never bundled. Only the configuration this generated project',
        '# needs is set here; everything else keeps the Ren\'Py 8.5.4 defaults.',
        '',
        'define config.name = ' + literal(title),
        'define config.version = ' + literal(version),
        'define build.name = ' + literal(slug),
        'define build.version = ' + literal(FORMAT_VERSION),
        'define config.save_directory = ' + literal('PoemSeed-' + slug + '-B07'),
        '',
        '# The generated say statements escape percent signs for the legacy',
        '# substitution mode; keep it enabled so a doubled percent renders as one percent.',
        'define config.old_substitutions = True',
        '',
    ]
    return '\n'.join(lines)


def _media_lines(media_references):
    if not media_references:
        return ['- none: the approved story references no media assets.']
    lines = []
    for item in media_references[:20]:
        lines.append('- ' + comment_text(str(item.get('asset_id')), 120) + ' (' + comment_text(str(item.get('kind')), 20) +
                     ', version ' + comment_text(str(item.get('version')), 20) + ', packaged: no' +
                     (', missing on the generation host' if item.get('missing') else '') + ')')
    if len(media_references) > 20:
        lines.append('- ... ' + str(len(media_references) - 20) + ' more reference(s), see the export manifest.')
    return lines


