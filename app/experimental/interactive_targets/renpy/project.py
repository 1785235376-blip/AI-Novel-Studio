def comment_text(value, limit=200):
    """Flatten one untrusted-ish value so it can never break a comment line."""
    if not isinstance(value, str):
        value = '' if value is None else str(value)
    cleaned = ''.join(' ' if ch in '\r\n\t\u0085\u2028\u2029\ufeff' or ord(ch) < 32 else ch for ch in value)
    return cleaned[:limit]


def literal(value):
    """Emit one displayed-text literal through the story authority escaper."""
    return renpy_text(value)


def scalar_literal(value):
    """Emit a strict bool/int initial value or assignment value."""
    if type(value) is bool:
        return 'True' if value else 'False'
    if type(value) is int:
        return str(value)
    raise ValueError('RENPY_NON_SCALAR_VALUE')


def encode_json(value):
    """Deterministic UTF-8 JSON bytes for acceptance records."""
    return (json.dumps(value, ensure_ascii=False, sort_keys=True, indent=2) + '\n').encode('utf-8')


def projection(spec):
    """Compile the approved spec once and derive the deterministic label/name map."""
    spec = StorySpec.model_validate(spec).model_dump()
    nodes, compiled, issues = compile_story(spec)
    if issues:
        raise ValueError('RENPY_STORY_COMPILE_ISSUE:' + str(issues[0].get('code')))
    labels = {node_id: 'ans_node_' + str(index) for index, node_id in enumerate(nodes)}
    names = {value['name']: 'ans_var_' + str(index) for index, value in enumerate(spec['variables'])}
    return {'spec': spec, 'nodes': nodes, 'compiled': compiled, 'labels': labels, 'names': names}


